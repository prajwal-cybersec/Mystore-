import asyncio
import json
import os
import sys
from pathlib import Path

# Add backend to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "backend"))

from app.database import async_session_factory
from sqlalchemy import text

async def generate_coverage_report():
    async with async_session_factory() as session:
        res = await session.execute(
            text("""
                SELECT id, sku, name, brand, category, tryon_supported, tryon_type, tryon_asset, tryon_config
                FROM products
                ORDER BY tryon_supported DESC, category, sku ASC
            """)
        )
        products = res.mappings().all()

    root_dir = Path(__file__).resolve().parent.parent.parent
    static_dir = root_dir / "backend" / "app" / "static"

    lines = [
        "# Try-On Feature Product Coverage Report",
        "",
        f"**Generated on**: 2026-11-21  ",
        f"**Total Catalogue Products**: {len(products)}  ",
        "",
        "| SKU | Product Name | Category | Try-On Type | Asset Status | Calibrated | Try-On Enabled |",
        "|---|---|---|---|---|---|---|"
    ]

    supported_count = 0
    unsupported_count = 0
    asset_ready_count = 0

    for p in products:
        sku = p["sku"]
        name = p["name"]
        cat = p["category"]
        supported = p["tryon_supported"]
        ttype = p["tryon_type"] or "unsupported"
        asset = p["tryon_asset"]
        cfg = p["tryon_config"]
        if isinstance(cfg, str):
            try: cfg = json.loads(cfg)
            except: cfg = {}
        elif not cfg:
            cfg = {}

        is_calibrated = "Yes" if cfg and len(cfg) > 0 else "No"

        # Check asset status
        if not supported:
            asset_status = "N/A"
            unsupported_count += 1
        elif ttype in ["lipstick", "blush"]:
            asset_status = "✅ Color Vectors (No File Needed)"
            supported_count += 1
            asset_ready_count += 1
        elif asset:
            # Check if file exists on disk
            rel_path = asset.replace("/public/", "").replace("/static/", "")
            full_path = static_dir / rel_path
            if full_path.exists():
                asset_status = f"✅ Ready (`{full_path.name}`)"
                asset_ready_count += 1
            else:
                asset_status = f"⚠️ Needs Asset (`{asset}`)"
            supported_count += 1
        else:
            asset_status = "⚠️ Needs Asset"
            supported_count += 1

        enabled_badge = "✅ YES" if supported else "❌ NO"
        lines.append(f"| **{sku}** | {name[:38]} | {cat} | `{ttype}` | {asset_status} | {is_calibrated} | {enabled_badge} |")

    lines.extend([
        "",
        "---",
        "",
        "## Summary Statistics",
        "",
        f"- **Total Products**: {len(products)}",
        f"- **Try-On Supported Products**: {supported_count} ({round((supported_count/len(products))*100, 1)}%)",
        f"- **Assets Ready / Configured**: {asset_ready_count}",
        f"- **Unsupported Products (Hardware, Bottomwear, etc.)**: {unsupported_count}",
        "",
        "## Product Category to Tracking Mapping",
        "",
        "| Category / Subcategory | Tracking Engine | tryon_type | Status |",
        "|---|---|---|---|",
        "| **Fashion / T-Shirts** | PoseLandmarker (Shoulders 11, 12, Hips 23, 24) | `tshirt` | ✅ Supported |",
        "| **Fashion / Shirts & Kurtas** | PoseLandmarker (Shoulders 11, 12, Hips 23, 24) | `shirt` | ✅ Supported |",
        "| **Beauty / Lipstick** | FaceLandmarker (Lips contour 61, 291, 0, 17) | `lipstick` | ✅ Supported |",
        "| **Beauty / Blush** | FaceLandmarker (Cheeks 116, 345) | `blush` | ✅ Supported |",
        "| **Electronics / Headphones** | FaceLandmarker (Ears 234, 454 & Crown 10) | `headphones` | ✅ Supported |",
        "| **Accessories / Glasses** | FaceLandmarker (Eye Bridge 168) | `glasses` | 🟡 Ready for Catalog Addition |",
        "| **Jewellery / Earrings** | FaceLandmarker (Earlobes 177, 401) | `earrings` | 🟡 Ready for Catalog Addition |",
        "| **Accessories / Watches** | HandLandmarker (Wrist 0, Middle MCP 9) | `watch` | 🟡 Ready for Catalog Addition |",
        "| **Fashion / Sarees** | N/A (6-yard body drape) | `unsupported` | ⚪ Unsupported |",
        "| **Fashion / Bottomwear (Jeans, Trousers)**| N/A (Lower body obstruction) | `unsupported` | ⚪ Unsupported |",
        "| **Mobiles / Smartphones** | N/A (Handheld device) | `unsupported` | ⚪ Unsupported |",
        "| **Appliances / TV, Refrigerators** | N/A (Home appliances) | `unsupported` | ⚪ Unsupported |",
        "| **Electronics / Chargers & Powerbanks** | N/A (Accessories) | `unsupported` | ⚪ Unsupported |",
        "",
        "---",
        "*Report automatically generated by `backend/scripts/generate_coverage_report.py`.*"
    ])

    root_dir = Path(__file__).resolve().parent.parent.parent
    docs_dir = root_dir / "docs"
    docs_dir.mkdir(parents=True, exist_ok=True)
    report_path = docs_dir / "TRYON_COVERAGE.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Coverage report generated at: {report_path}")

if __name__ == "__main__":
    asyncio.run(generate_coverage_report())
